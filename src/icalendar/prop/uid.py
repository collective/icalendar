"""UID values from :rfc:`9253`."""

import re
import uuid
from typing import Any, ClassVar

from icalendar.compatibility import Self

from .text import vText

_IANA_TOKEN_RE = re.compile(r"^[A-Za-z0-9-]+$")


def validate_uid(value: Any) -> None:
    """Validate that a UID value conforms to :rfc:`7986#section-5.3` and :rfc:`5545#section-3.1`.

    According to :rfc:`7986#section-5.3`, UID values must not include any data
    that might identify a user, host, domain, or any other security- or
    privacy-sensitive information. UID values must have a length less than
    255 octets and must conform to the ``iana-token`` ABNF syntax defined in
    :rfc:`5545#section-3.1`: ``1*(ALPHA / DIGIT / "-")``. Hex-encoded random
    UUID values (such as those generated by :func:`uuid.uuid4` per :rfc:`4122`)
    conform to this syntax.

    Parameters:
        value: The UID value to validate. Must be a :class:`str` or :class:`uuid.UUID`.

    Raises:
        TypeError: If ``value`` is neither a :class:`str` nor a :class:`uuid.UUID`.
        ValueError: If ``value`` is empty, has a length of 255 octets or more,
            or contains characters other than ASCII alphanumeric characters and hyphens.

    .. note::

        Although the ``iana-token`` ABNF syntax is case-insensitive in the RFC grammar,
        the UID value preserves its original letter casing and is not converted.
    """
    if isinstance(value, uuid.UUID):
        uid_str = str(value)
    elif isinstance(value, str):
        uid_str = value
    else:
        raise TypeError(
            f"UID must be a string or uuid.UUID, got {type(value).__name__}."
        )

    if not uid_str:
        raise ValueError("UID must not be empty.")

    encoded = uid_str.encode("utf-8")
    if len(encoded) >= 255:
        raise ValueError(
            f"UID must have a length less than 255 octets, got {len(encoded)} octets."
        )

    if not _IANA_TOKEN_RE.match(uid_str):
        raise ValueError(
            f"UID {uid_str!r} is invalid: must conform to the iana-token syntax "
            "(only ASCII alphanumeric characters and hyphens) per RFC 7986 Section 5.3."
        )


class vUid(vText):
    """A UID of a component.

    This is defined in :rfc:`9253`, Section 7.
    """

    default_value: ClassVar[str] = "UID"

    @classmethod
    def new(cls) -> Self:
        """Create a new UID for convenience.

        .. code-block:: pycon

            >>> from icalendar import vUid
            >>> vUid.new()
            vUid('d755cef5-2311-46ed-a0e1-6733c9e15c63')

        """
        return cls(str(uuid.uuid4()))

    @property
    def uid(self) -> str:
        """The UID of this property."""
        return str(self)

    @property
    def ical_value(self) -> str:
        """The UID of this property."""
        return self.uid

    def __repr__(self) -> str:
        """repr(self)"""
        return f"{self.__class__.__name__}({self.uid!r})"

    from icalendar.param import FMTTYPE, LABEL, LINKREL

    @classmethod
    def examples(cls) -> list[Self]:
        """Examples of vUid."""
        return [cls("d755cef5-2311-46ed-a0e1-6733c9e15c63")]

    @classmethod
    def validate(cls, value: Any) -> None:
        """Validate that a UID value conforms to RFC 7986 and RFC 5545."""
        validate_uid(value)


__all__ = ["vUid", "validate_uid"]
